using System;
using System.IO;
using DG.Tweening;
using SafeArea;
using OpenSekai.Shared.Packages;
using Sekai.UI;
using UnityEngine;

namespace Sekai.Live
{
	/// <summary>
	/// The song info page shown before a live: a dark band across the screen with the jacket on the
	/// left and the title, credits and chart credits on the right. One DOTween sequence drives the
	/// whole page (about 2.9 s at the default scale): the band opens, the jacket and the text rows
	/// slide in, a light sweeps over the jacket, then everything fades out. The layout lives in
	/// <c>FrontUIView.prefab</c> and is generated by <c>OpenSekai/Art/Rebuild Music Info Page</c>.
	/// </summary>
	public class MusicInfoView : MonoBehaviour
	{
		[SerializeField]
		private SafeAreaAdjuster _safeAreaAdjuster;

		[SerializeField]
		private CanvasGroup _viewGroup;

		/// <summary>Text rows, in the order they slide in.</summary>
		[SerializeField]
		private CanvasGroup[] _infoGroup;

		[SerializeField]
		private RectTransform _band;

		[SerializeField]
		private RectTransform[] _bandEdges;

		[SerializeField]
		private CanvasGroup _jacketGroup;

		[SerializeField]
		private RectTransform _shine;

		[SerializeField]
		private RectTransform _rule;

		[SerializeField]
		private RectTransform[] _sparkles;

		[SerializeField]
		private RectTransform _textColumn;

		[SerializeField]
		private CustomRawImage _jacket;

		[SerializeField]
		private UIPartsMusicDifficulty _difficultyJacket;

		[SerializeField]
		private CustomTextMesh _difficultyJacketText;

		[SerializeField]
		private CustomTextMesh _titleLabel;

		[SerializeField]
		private CustomTextMesh _creatorLabel;

		[SerializeField]
		private CustomTextMesh _singerLabel;

		[SerializeField]
		private UIPartsMusicCollaborationRibbon _collaborationRibbon;

		[SerializeField]
		private GameObject _musicInfoRoot;

		[SerializeField]
		private GameObject _scoreInfoRoot;

		[SerializeField]
		private CustomTextMesh _scoreTitleLabel;

		[SerializeField]
		private CustomTextMesh _scoreCreatorLabel;

		[SerializeField]
		private GameObject _scoreIcon;

		/// <summary>How long the page holds before it starts fading out, in seconds at scale 1.</summary>
		[SerializeField]
		private float _JacketFadeOutDelaySec = 2.35f;

		private const string CREATOR_WORDING_KEY = "MSG_CREATOR_NAME";
		private const string SINGER_WORDING_KEY = "MSG_SINGER_NAME";
		private const string INSTRUMENTAL_VOCAL_NAMES_WORDING_KEY = "WORD_INSTRUMENTLE_VERSION_NAMES";

		/// <summary>The text column drops this far when there are no chart credits, to stay centred.</summary>
		private const float NO_SCORE_INFO_COLUMN_OFFSET_Y = -52f;

		private const float START_DELAY = 0.01f;
		private const float FADE_OUT_DURATION = 0.45f;
		private const float VIEW_FADE_IN_DURATION = 0.25f;
		private const float JACKET_SLIDE_X = -90f;
		private const float ROW_SLIDE_X = 70f;
		private const float SHINE_TRAVEL_X = 430f;
		private const float EXIT_DRIFT_X = -36f;

		public float JacketFadeOutDelaySec
		{
			get => _JacketFadeOutDelaySec;
			set => _JacketFadeOutDelaySec = value;
		}

		private bool _playStartEffectEnabled;
		private Sequence _sequence;
		private Vector2 _textColumnBasePosition;
		/// <summary>Where the column rests for the current song (base, dropped when there are no chart credits).</summary>
		private Vector2 _textColumnPosition;
		private bool _hasLayoutCache;
		private Vector2 _jacketBasePosition;
		private Vector2[] _rowBasePositions = Array.Empty<Vector2>();

		public float AnimationDurationSec => PlayDurationSeconds;

		/// <summary>
		/// How long <see cref="Play"/> at its default scale keeps the page up: the short start delay,
		/// the hold, then the fade-out.
		/// </summary>
		public float PlayDurationSeconds => START_DELAY + Mathf.Max(0f, JacketFadeOutDelaySec) + FADE_OUT_DURATION;

		public void Setup(LiveBootDataBase bootData)
		{
			LiveMusicData musicData = bootData?.MusicData;
			_playStartEffectEnabled = musicData?.PlayStartEffectEnabled ?? true;
			KillSequence();
			CacheLayout();
			ResetToHidden();

			_difficultyJacket?.Setup(musicData?.DifficultyEnum ?? MusicDifficulty.none);
			SetupDifficulty(musicData?.DifficultyString);

			FreeLiveBootData freeLiveBootData = bootData as FreeLiveBootData;
			bool isCustomScore = freeLiveBootData != null && bootData.IsCustomMusicScore;
			bool showCustomScoreInfo = isCustomScore && (bootData.LiveSettingData?.UsesCustomMusicScoreMusicInfoDisplay ?? true);
			_scoreIcon?.SetActive(showCustomScoreInfo);
			_scoreInfoRoot?.SetActive(showCustomScoreInfo);
			_textColumnPosition = _textColumnBasePosition + (showCustomScoreInfo ? Vector2.zero : new Vector2(0f, NO_SCORE_INFO_COLUMN_OFFSET_Y));
			if (_textColumn != null)
			{
				_textColumn.anchoredPosition = _textColumnPosition;
			}

			string title = musicData?.Music?.title ?? string.Empty;
			string lyricist = musicData?.Music?.lyricist ?? string.Empty;
			string composer = musicData?.Music?.composer ?? string.Empty;
			string arranger = musicData?.Music?.arranger ?? string.Empty;
			string singer = ResolveVocalText(musicData?.Vocal, string.Empty);

			_titleLabel?.SetText(title);
			_creatorLabel?.SetWordingText(CREATOR_WORDING_KEY, lyricist, composer, arranger);
			_singerLabel?.SetWordingText(SINGER_WORDING_KEY, singer);

			if (_collaborationRibbon != null)
			{
				string collaborationLabel = ResolveCollaborationLabel(freeLiveBootData, isCustomScore);
				bool hasCollaboration = !string.IsNullOrWhiteSpace(collaborationLabel);
				_collaborationRibbon.gameObject.SetActive(hasCollaboration);
				if (hasCollaboration)
				{
					_collaborationRibbon.SetText(collaborationLabel);
				}
			}

			if (showCustomScoreInfo)
			{
				_scoreTitleLabel?.SetText(freeLiveBootData.CustomMusicScoreTitle ?? title);
				_scoreCreatorLabel?.SetText(freeLiveBootData.CustomMusicScoreAuthorName ?? string.Empty);
			}

			Texture2D texture = LoadJacketTexture(bootData, musicData);
			if (_jacket != null)
			{
				_jacket.texture = texture;
				_jacket.enabled = texture != null;
			}
		}

		private void SetupDifficulty(string difficulty)
		{
			if (string.IsNullOrEmpty(difficulty))
			{
				difficulty = "none";
			}

			_difficultyJacket?.Setup(difficulty);
			if (_difficultyJacketText != null)
			{
				_difficultyJacketText.SetText(difficulty.ToUpperInvariant());
				_difficultyJacketText.gameObject.SetActive(true);
			}
		}

		/// <param name="durationScale">Stretches every time on the page's timeline.</param>
		/// <param name="disableOnlyJacketOnFinish">At the end, fade only the content and keep the band up.</param>
		/// <param name="bgFadeoutDuration">Extra hold added before the fade-out.</param>
		/// <param name="onFinish">Called once the page has faded out and been switched off.</param>
		/// <param name="onFinishViewGroupFade">Called once the band has faded in.</param>
		public void Play(float durationScale = 1f, bool disableOnlyJacketOnFinish = false, float bgFadeoutDuration = 0f, Action onFinish = null, Action onFinishViewGroupFade = null)
		{
			if (!_playStartEffectEnabled)
			{
				gameObject.SetActive(false);
				return;
			}

			KillSequence();
			CacheLayout();
			_safeAreaAdjuster?.Setup();
			_safeAreaAdjuster?.Apply();
			ResetToHidden();

			float s = Mathf.Max(durationScale, 0.001f);
			float exitAt = START_DELAY * s + Mathf.Max(0f, JacketFadeOutDelaySec * s + bgFadeoutDuration);
			float fade = FADE_OUT_DURATION * s;

			gameObject.SetActive(true);
			Sequence seq = DOTween.Sequence().SetUpdate(true);
			float t0 = START_DELAY * s;

			// The band opens from a line, then its edge rules draw outwards.
			if (_viewGroup != null)
			{
				seq.Insert(t0, _viewGroup.DOFade(1f, VIEW_FADE_IN_DURATION * s).SetEase(Ease.OutQuad));
			}
			seq.InsertCallback(t0 + VIEW_FADE_IN_DURATION * s, () => onFinishViewGroupFade?.Invoke());
			if (_band != null)
			{
				seq.Insert(t0, _band.DOScaleY(1f, 0.38f * s).SetEase(Ease.OutCubic));
			}
			if (_bandEdges != null)
			{
				foreach (RectTransform edge in _bandEdges)
				{
					if (edge != null)
					{
						seq.Insert(t0 + 0.06f * s, edge.DOScaleX(1f, 0.5f * s).SetEase(Ease.OutQuart));
					}
				}
			}

			// Jacket slides in from the left and settles from a slight zoom.
			if (_jacketGroup != null)
			{
				RectTransform jacketRect = (RectTransform)_jacketGroup.transform;
				seq.Insert(t0 + 0.1f * s, _jacketGroup.DOFade(1f, 0.3f * s).SetEase(Ease.OutQuad));
				seq.Insert(t0 + 0.1f * s, jacketRect.DOAnchorPos(_jacketBasePosition, 0.48f * s).SetEase(Ease.OutCubic));
				seq.Insert(t0 + 0.1f * s, jacketRect.DOScale(1f, 0.55f * s).SetEase(Ease.OutCubic));
			}
			if (_shine != null)
			{
				seq.Insert(t0 + 0.55f * s, _shine.DOAnchorPosX(SHINE_TRAVEL_X, 0.6f * s).SetEase(Ease.InOutSine));
			}

			// Text rows follow one after another from the right.
			if (_infoGroup != null)
			{
				for (int i = 0; i < _infoGroup.Length; i++)
				{
					CanvasGroup row = _infoGroup[i];
					if (row == null)
					{
						continue;
					}
					float at = t0 + (0.24f + 0.07f * i) * s;
					seq.Insert(at, row.DOFade(1f, 0.32f * s).SetEase(Ease.OutQuad));
					seq.Insert(at, ((RectTransform)row.transform).DOAnchorPos(_rowBasePositions[i], 0.42f * s).SetEase(Ease.OutCubic));
				}
			}
			if (_rule != null)
			{
				seq.Insert(t0 + 0.36f * s, _rule.DOScaleX(1f, 0.55f * s).SetEase(Ease.OutQuart));
			}

			// Sparkles pop in around the frame and keep turning slowly until the page leaves.
			if (_sparkles != null)
			{
				for (int i = 0; i < _sparkles.Length; i++)
				{
					RectTransform sparkle = _sparkles[i];
					if (sparkle == null)
					{
						continue;
					}
					float at = t0 + (0.45f + 0.09f * i) * s;
					seq.Insert(at, sparkle.DOScale(1f, 0.35f * s).SetEase(Ease.OutBack, 2.2f));
					float turn = (i % 2 == 0 ? 1f : -1f) * 70f;
					seq.Insert(at, sparkle.DOLocalRotate(new Vector3(0f, 0f, turn), Mathf.Max(0.01f, exitAt + fade - at), RotateMode.FastBeyond360).SetEase(Ease.OutSine));
				}
			}

			// Exit: content drifts left while the page fades.
			if (disableOnlyJacketOnFinish)
			{
				AppendContentFadeOut(seq, exitAt, fade);
			}
			else
			{
				if (_jacketGroup != null)
				{
					seq.Insert(exitAt, ((RectTransform)_jacketGroup.transform).DOAnchorPosX(_jacketBasePosition.x + EXIT_DRIFT_X, fade).SetEase(Ease.InQuad));
				}
				if (_textColumn != null)
				{
					seq.Insert(exitAt, _textColumn.DOAnchorPosX(_textColumnPosition.x + EXIT_DRIFT_X, fade).SetEase(Ease.InQuad));
				}
				if (_band != null)
				{
					seq.Insert(exitAt, _band.DOScaleY(0.6f, fade).SetEase(Ease.InQuad));
				}
				if (_viewGroup != null)
				{
					seq.Insert(exitAt, _viewGroup.DOFade(0f, fade).SetEase(Ease.InQuad));
				}
				seq.InsertCallback(exitAt + fade, () =>
				{
					if (this == null)
					{
						return;
					}
					gameObject.SetActive(false);
					onFinish?.Invoke();
				});
			}

			_sequence = seq;
		}

		private void AppendContentFadeOut(Sequence seq, float at, float fade)
		{
			if (_jacketGroup != null)
			{
				seq.Insert(at, _jacketGroup.DOFade(0f, fade));
			}
			if (_infoGroup == null)
			{
				return;
			}
			foreach (CanvasGroup row in _infoGroup)
			{
				if (row != null)
				{
					seq.Insert(at, row.DOFade(0f, fade));
				}
			}
		}

		public void FadeViewGroup(float alpha)
		{
			if (_viewGroup != null)
			{
				_viewGroup.alpha = alpha;
			}
		}

		private void OnDisable()
		{
			KillSequence();
		}

		private void OnDestroy()
		{
			KillSequence();
		}

		/// <summary>Remembers where the prefab puts each animated element, before anything moves it.</summary>
		private void CacheLayout()
		{
			if (_hasLayoutCache)
			{
				return;
			}
			_hasLayoutCache = true;
			if (_textColumn != null)
			{
				_textColumnBasePosition = _textColumn.anchoredPosition;
				_textColumnPosition = _textColumnBasePosition;
			}
			if (_jacketGroup != null)
			{
				_jacketBasePosition = ((RectTransform)_jacketGroup.transform).anchoredPosition;
			}
			int count = _infoGroup?.Length ?? 0;
			_rowBasePositions = new Vector2[count];
			for (int i = 0; i < count; i++)
			{
				if (_infoGroup[i] != null)
				{
					_rowBasePositions[i] = ((RectTransform)_infoGroup[i].transform).anchoredPosition;
				}
			}
		}

		/// <summary>Puts every animated element at the start of the timeline.</summary>
		private void ResetToHidden()
		{
			// The exit drifts the column left; a retry replays on the same view, so put it back.
			if (_textColumn != null)
			{
				_textColumn.anchoredPosition = _textColumnPosition;
			}
			if (_viewGroup != null)
			{
				_viewGroup.alpha = 0f;
			}
			if (_band != null)
			{
				_band.localScale = new Vector3(1f, 0f, 1f);
			}
			if (_bandEdges != null)
			{
				foreach (RectTransform edge in _bandEdges)
				{
					if (edge != null)
					{
						edge.localScale = new Vector3(0f, 1f, 1f);
					}
				}
			}
			if (_jacketGroup != null)
			{
				_jacketGroup.alpha = 0f;
				RectTransform jacketRect = (RectTransform)_jacketGroup.transform;
				jacketRect.anchoredPosition = _jacketBasePosition + new Vector2(JACKET_SLIDE_X, 0f);
				jacketRect.localScale = Vector3.one * 1.06f;
			}
			if (_shine != null)
			{
				_shine.anchoredPosition = new Vector2(-SHINE_TRAVEL_X, _shine.anchoredPosition.y);
			}
			if (_rule != null)
			{
				_rule.localScale = new Vector3(0f, 1f, 1f);
			}
			if (_infoGroup != null)
			{
				for (int i = 0; i < _infoGroup.Length; i++)
				{
					CanvasGroup row = _infoGroup[i];
					if (row == null)
					{
						continue;
					}
					row.alpha = 0f;
					((RectTransform)row.transform).anchoredPosition = _rowBasePositions[i] + new Vector2(ROW_SLIDE_X, 0f);
				}
			}
			if (_sparkles != null)
			{
				foreach (RectTransform sparkle in _sparkles)
				{
					if (sparkle != null)
					{
						sparkle.localScale = Vector3.zero;
						sparkle.localRotation = Quaternion.identity;
					}
				}
			}
		}

		private void KillSequence()
		{
			if (_sequence != null && _sequence.IsActive())
			{
				_sequence.Kill();
			}
			_sequence = null;
		}

		private static string ResolveVocalText(MasterMusicVocal vocal, string fallback)
		{
			if (vocal == null)
			{
				return fallback ?? string.Empty;
			}

			if (string.Equals(vocal.musicVocalType, MusicVocalType.instrumental.ToString(), StringComparison.OrdinalIgnoreCase))
			{
				return WordingManager.Get(INSTRUMENTAL_VOCAL_NAMES_WORDING_KEY);
			}

			if (!string.IsNullOrEmpty(vocal.caption))
			{
				return vocal.caption;
			}

			return fallback ?? string.Empty;
		}

		private static string ResolveCollaborationLabel(FreeLiveBootData freeLiveBootData, bool isCustomScore)
		{
			if (isCustomScore && freeLiveBootData != null)
			{
				return freeLiveBootData.CustomMusicScoreCollaborationLabel;
			}

			return string.Empty;
		}

		private static Texture2D LoadJacketTexture(LiveBootDataBase bootData, LiveMusicData musicData)
		{
			Texture2D customTexture = LoadCustomJacketTexture(bootData as FreeLiveBootData);
			if (customTexture != null)
			{
				return customTexture;
			}

			int musicId = musicData?.Music?.id ?? 0;
			string resourceName = musicId > 0 ? $"jacket_s_{musicId}" : null;
			if (string.IsNullOrEmpty(resourceName))
			{
				return null;
			}

			Texture2D texture = AssetBundleUtility.LoadAsset<Texture2D>("thumbnail/music_jacket", resourceName, false);
			if (texture == null)
			{
				texture = AssetBundleUtility.LoadAsset<Texture2D>("startapp/thumbnail/music_jacket", resourceName, false);
			}
			return texture;
		}

		private static Texture2D LoadCustomJacketTexture(FreeLiveBootData bootData)
		{
			if (bootData == null || string.IsNullOrEmpty(bootData.CustomMusicScorePath))
			{
				return null;
			}

			try
			{
				// The jacket path alone is all this needs; the App-side entry wrapper also allocates
				// an audio object, which a view has no use for.
				SongPackage package = SongPackageStorage.LoadEntry(bootData.CustomMusicScorePath);
				string jacketPath = package?.JacketPath;
				if (string.IsNullOrEmpty(jacketPath) || !File.Exists(jacketPath))
				{
					return null;
				}

				Texture2D texture = new Texture2D(2, 2, TextureFormat.RGBA32, false);
				return ImageConversion.LoadImage(texture, File.ReadAllBytes(jacketPath)) ? texture : null;
			}
			catch
			{
				return null;
			}
		}
	}
}
