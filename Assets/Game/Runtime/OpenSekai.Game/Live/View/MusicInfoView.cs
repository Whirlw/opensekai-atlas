		public void Setup(LiveBootDataBase bootData)
		{
			LiveMusicData musicData = bootData?.MusicData;
			_playStartEffectEnabled = musicData?.PlayStartEffectEnabled ?? true;
			CancelAnimation();
			CacheLayout();
			ResetToHidden();

			difficultyJacket?.Setup(musicData?.DifficultyEnum ?? MusicDifficulty.none);
			SetupDifficulty(musicData?.DifficultyString);
			int level = musicData?.PlayLevel ?? 0;
			levelLabel?.SetText(level > 0 ? "LV " + level : string.Empty);

			FreeLiveBootData freeLiveBootData = bootData as FreeLiveBootData;
			bool isCustomScore = freeLiveBootData != null && bootData.IsCustomMusicScore;
			bool showCustomScoreInfo = isCustomScore && (bootData.LiveSettingData?.UsesCustomMusicScoreMusicInfoDisplay ?? true);
			scoreIcon?.SetActive(showCustomScoreInfo);
			scoreInfoRoot?.SetActive(showCustomScoreInfo);
			_textColumnPosition = _textColumnBasePosition + (showCustomScoreInfo ? Vector2.zero : new Vector2(0f, NO_SCORE_INFO_COLUMN_OFFSET_Y));
			if (textColumn != null)
			{
				textColumn.anchoredPosition = _textColumnPosition;
			}

			string title = musicData?.Music?.title ?? string.Empty;
			string lyricist = musicData?.Music?.lyricist ?? string.Empty;
			string composer = musicData?.Music?.composer ?? string.Empty;
			string arranger = musicData?.Music?.arranger ?? string.Empty;
			string singer = ResolveVocalText(musicData?.Vocal, string.Empty);

			titleLabel?.SetText(title);
			creatorLabel?.SetText(BuildCredits(lyricist, composer, arranger));
			// The layout captions the line 演唱, so the name goes in plain; the old "Vo." wording
			// would repeat it.
			singerLabel?.SetText(string.IsNullOrWhiteSpace(singer) ? "—" : singer);

			if (collaborationRibbon != null)
			{
				string collaborationLabel = ResolveCollaborationLabel(freeLiveBootData, isCustomScore);
				bool hasCollaboration = !string.IsNullOrWhiteSpace(collaborationLabel);
				collaborationRibbon.gameObject.SetActive(hasCollaboration);
				if (hasCollaboration)
				{
					collaborationRibbon.SetText(collaborationLabel);
				}
			}

			if (showCustomScoreInfo)
			{
				scoreTitleLabel?.SetText(freeLiveBootData.CustomMusicScoreTitle ?? title);
				scoreCreatorLabel?.SetText(freeLiveBootData.CustomMusicScoreAuthorName ?? string.Empty);
			}

			Texture2D texture = LoadJacketTexture(bootData, musicData);
			if (jacket != null)
			{
				jacket.texture = texture;
				jacket.enabled = texture != null;
			}

			PaletteOf(texture, out Color accent, out Color glow);
			JacketTexture = texture;
			Accent = accent;
			Tint(accentGraphics, accent);
			Tint(glowGraphics, glow);
		}

		/// <summary>
		/// The 创作 line: only the roles a package fills in, and one entry when the composer also
		/// arranged ("作曲・编曲 X"), rather than the fixed three-slot wording with dashes.
		/// </summary>
		private static string BuildCredits(string lyricist, string composer, string arranger)
		{
			static bool Has(string value) => !string.IsNullOrWhiteSpace(value) && value.Trim() != "-";
			var parts = new List<string>(3);
			if (Has(lyricist))
			{
				parts.Add("作词 " + lyricist.Trim());
			}
			if (Has(composer) && Has(arranger) && string.Equals(composer.Trim(), arranger.Trim(), StringComparison.Ordinal))
			{
				parts.Add("作曲・编曲 " + composer.Trim());
			}
			else
			{
				if (Has(composer)) parts.Add("作曲 " + composer.Trim());
				if (Has(arranger)) parts.Add("编曲 " + arranger.Trim());
			}
			return parts.Count > 0 ? string.Join("    ", parts) : "—";
		}

		/// <summary>Sets each graphic's color to <paramref name="color"/>, keeping the alpha the layout gave it.</summary>
		private static void Tint(Graphic[] graphics, Color color)
		{
			if (graphics == null)
			{
				return;
			}

			foreach (Graphic graphic in graphics)
			{
				if (graphic != null)
				{
					graphic.color = new Color(color.r, color.g, color.b, graphic.color.a);
				}
			}
		}

		/// <summary>
		/// The library's jacket palette (JacketPalette.From): the hue the jacket is mostly made of,
		/// vivid pixels weighing more than dull ones, as a light accent and a darker glow.
		/// </summary>
		private static void PaletteOf(Texture2D texture, out Color accent, out Color glow)
		{
			accent = _defaultAccent;
			glow = _defaultGlow;
			if (texture == null || !texture.isReadable)
			{
				return;
			}

			Color32[] pixels;
			try
			{
				pixels = texture.GetPixels32();
			}
			catch (UnityException)
			{
				return;
			}

			int step = Mathf.Max(1, pixels.Length / PALETTE_SAMPLES);
			double red = 0d, green = 0d, blue = 0d, weightSum = 0d;
			for (int i = 0; i < pixels.Length; i += step)
			{
				Color32 pixel = pixels[i];
				if (pixel.a < 32)
				{
					continue;
				}

				int max = Mathf.Max(pixel.r, Mathf.Max(pixel.g, pixel.b));
				int min = Mathf.Min(pixel.r, Mathf.Min(pixel.g, pixel.b));
				double weight = 1d + (max - min);
				red += pixel.r * weight;
				green += pixel.g * weight;
				blue += pixel.b * weight;
				weightSum += weight;
			}

			if (weightSum <= 0d)
			{
				return;
			}

			var average = new Color((float)(red / weightSum / 255d), (float)(green / weightSum / 255d), (float)(blue / weightSum / 255d));
			Color.RGBToHSV(average, out float hue, out float saturation, out float _);
			if (saturation < GRAY_SATURATION)
			{
				accent = _neutralAccent;
				glow = _neutralGlow;
				return;
			}

			accent = Color.HSVToRGB(hue, Mathf.Clamp(saturation, 0.28f, 0.45f), 1f);
			glow = Color.HSVToRGB(hue, Mathf.Clamp(saturation * 1.2f, 0.45f, 0.8f), 0.55f);
		}

		/// <summary>The library's label color for a difficulty (LibraryTheme.Colors.Difficulty).</summary>
		private static Color DifficultyColor(string difficulty)
		{
			switch ((difficulty ?? string.Empty).ToLowerInvariant())
			{
				case "easy": return new Color32(123, 216, 143, 255);
				case "normal": return new Color32(124, 200, 245, 255);
				case "hard": return new Color32(245, 196, 81, 255);
				case "expert": return new Color32(245, 154, 154, 255);
				case "master": return new Color32(205, 166, 245, 255);
				case "append": return new Color32(242, 176, 222, 255);
				default: return _difficultyFallback;
			}
		}

		private void SetupDifficulty(string difficulty)
		{
			if (string.IsNullOrEmpty(difficulty))
			{
				difficulty = "none";
			}

			difficultyJacket?.Setup(difficulty);
			if (difficultyJacketText != null)
			{
				difficultyJacketText.SetText(difficulty.ToUpperInvariant());
				difficultyJacketText.gameObject.SetActive(true);
			}

			Color color = DifficultyColor(difficulty);
			Tint(difficultyGraphics, color);
		}

		/// <param name="durationScale">Stretches every time on the page's timeline.</param>
		/// <param name="disableOnlyJacketOnFinish">At the end, fade only the content and keep the band up.</param>
		/// <param name="bgFadeoutDuration">Extra hold added before the fade-out.</param>
		/// <param name="onFinish">Called once the page has faded out and been switched off.</param>
		/// <param name="onFinishViewGroupFade">Called once the band has faded in.</param>
		public void Play(float durationScale = 1f, bool disableOnlyJacketOnFinish = false, float bgFadeoutDuration = 0f, Action onFinish = null, Action onFinishViewGroupFade = null)
		{
			// The first time the page comes up it is already there under the library's loading
			// screen, which fades out over it; a page fading in at the same moment flashes the live
			// through both. Only a retry, which has nothing covering it, opens the page.
			bool opensPage = _hasPlayed;
			_hasPlayed = true;
			CancelAnimation();
			if (!_playStartEffectEnabled)
			{
				gameObject.SetActive(false);
				return;
			}

			CacheLayout();
			safeAreaAdjuster?.Setup();
			safeAreaAdjuster?.Apply();
			ResetToHidden();
			gameObject.SetActive(true);

			float s = Mathf.Max(durationScale, 0.001f);
			float t0 = START_DELAY * s;
			float fadeInEnd = t0 + VIEW_FADE_IN_DURATION * s;
			float exitAt = t0 + Mathf.Max(0f, JacketFadeOutDelaySec * s + bgFadeoutDuration);
			float fade = FADE_OUT_DURATION * s;
			float exitEnd = exitAt + fade;
			float duration = exitEnd;
			float previous = -1f;
			var tracks = new List<Action<float>>();

			void Track(float start, float length, Ease ease, Action<float> apply, float stop = float.PositiveInfinity)
			{
				AddTrack(start, length, stop, progress => apply(EaseUtility.Evaluate(progress, ease)));
			}

			void AddTrack(float start, float length, float stop, Action<float> apply)
			{
				float end = Mathf.Min(start + length, stop);
				if (start >= end)
				{
					return;
				}
				duration = Mathf.Max(duration, end);
				tracks.Add(time =>
				{
					if (time >= start && previous < end)
					{
						apply(Mathf.Clamp01((Mathf.Min(time, end) - start) / length));
					}
				});
			}

			// Entrance tracks that share an exit property stop at the exit boundary. The exit
			// samples that value after the entrance has been evaluated, even on a large frame step.
			void Exit(float target, Ease ease, Func<float> read, Action<float> write)
			{
				float from = 0f;
				Track(exitAt, fade, ease, progress =>
				{
					if (previous < exitAt)
					{
						from = read();
					}
					write(Mathf.LerpUnclamped(from, target, progress));
				});
			}

			float pageExit = disableOnlyJacketOnFinish ? float.PositiveInfinity : exitAt;
			float contentExit = disableOnlyJacketOnFinish ? exitAt : float.PositiveInfinity;
			if (!opensPage)
			{
				if (viewGroup != null)
				{
					viewGroup.alpha = 1f;
				}
				if (band != null)
				{
					SetScaleY(band, 1f);
				}
			}
			else
			{
				if (viewGroup != null)
				{
					Track(t0, VIEW_FADE_IN_DURATION * s, Ease.OutQuad, p => viewGroup.alpha = p, pageExit);
				}
				if (band != null)
				{
					Track(t0, 0.38f * s, Ease.OutCubic, p => SetScaleY(band, p), pageExit);
				}
			}
			if (bandEdges != null)
			{
				foreach (RectTransform edge in bandEdges)
				{
					if (edge != null)
					{
						Track(t0 + 0.06f * s, 0.5f * s, Ease.OutQuart, p => SetScaleX(edge, p));
					}
				}
			}

			if (jacketGroup != null)
			{
				RectTransform rect = (RectTransform)jacketGroup.transform;
				Vector2 from = rect.anchoredPosition;
				Track(t0 + 0.1f * s, 0.3f * s, Ease.OutQuad, p => jacketGroup.alpha = p, contentExit);
				Track(t0 + 0.1f * s, 0.48f * s, Ease.OutCubic,
					p => rect.anchoredPosition = Vector2.LerpUnclamped(from, _jacketBasePosition, p), pageExit);
				Track(t0 + 0.1f * s, 0.55f * s, Ease.OutCubic,
					p => rect.localScale = Vector3.one * Mathf.LerpUnclamped(1.06f, 1f, p));
			}
			if (shine != null)
			{
				Track(t0 + 0.55f * s, 0.6f * s, Ease.InOutSine,
					p => SetPositionX(shine, Mathf.LerpUnclamped(-SHINE_TRAVEL_X, SHINE_TRAVEL_X, p)));
			}

			if (infoGroup != null)
			{
				for (int i = 0; i < infoGroup.Length; i++)
				{
					CanvasGroup row = infoGroup[i];
					if (row == null)
					{
						continue;
					}

					RectTransform rect = (RectTransform)row.transform;
					Vector2 from = rect.anchoredPosition;
					Vector2 to = _rowBasePositions[i];
					float at = t0 + (0.24f + 0.07f * i) * s;
					Track(at, 0.32f * s, Ease.OutQuad, p => row.alpha = p, contentExit);
					Track(at, 0.42f * s, Ease.OutCubic, p => rect.anchoredPosition = Vector2.LerpUnclamped(from, to, p));
				}
			}
			if (rule != null)
			{
				Track(t0 + 0.36f * s, 0.55f * s, Ease.OutQuart, p => SetScaleX(rule, p));
			}
			if (sparkles != null)
			{
				for (int i = 0; i < sparkles.Length; i++)
				{
					RectTransform sparkle = sparkles[i];
					if (sparkle == null)
					{
						continue;
					}

					float at = t0 + (0.45f + 0.09f * i) * s;
					float turn = (i % 2 == 0 ? 1f : -1f) * 70f;
					AddTrack(at, 0.35f * s, float.PositiveInfinity, p =>
					{
						// Preserve the original OutBack overshoot of 2.2.
						float x = p - 1f;
						sparkle.localScale = Vector3.one * (1f + x * x * (3.2f * x + 2.2f));
					});
					Track(at, Mathf.Max(0.01f, exitEnd - at), Ease.OutSine,
						p => sparkle.localRotation = Quaternion.Euler(0f, 0f, turn * p));
				}
			}

			if (disableOnlyJacketOnFinish)
			{
				if (jacketGroup != null)
				{
					Exit(0f, Ease.OutQuad, () => jacketGroup.alpha, a => jacketGroup.alpha = a);
				}
				if (infoGroup != null)
				{
					foreach (CanvasGroup row in infoGroup)
					{
						if (row != null)
						{
							Exit(0f, Ease.OutQuad, () => row.alpha, a => row.alpha = a);
						}
					}
				}
			}
			else
			{
				if (jacketGroup != null)
				{
					RectTransform rect = (RectTransform)jacketGroup.transform;
					Exit(_jacketBasePosition.x + EXIT_DRIFT_X, Ease.InQuad, () => rect.anchoredPosition.x, x => SetPositionX(rect, x));
				}
				if (textColumn != null)
				{
					Exit(_textColumnPosition.x + EXIT_DRIFT_X, Ease.InQuad,
						() => textColumn.anchoredPosition.x, x => SetPositionX(textColumn, x));
				}
				if (band != null)
				{
					Exit(0.6f, Ease.InQuad, () => band.localScale.y, y => SetScaleY(band, y));
				}
				if (viewGroup != null)
				{
					Exit(0f, Ease.InQuad, () => viewGroup.alpha, a => viewGroup.alpha = a);
				}
				duration = exitEnd;
			}

			void Render(float elapsed)
			{
				foreach (Action<float> track in tracks)
				{
					track(elapsed);
				}
				previous = elapsed;
			}

			int playVersion = _playVersion;
			_animation = LMotion.Create(0f, duration, duration)
				.WithScheduler(LiveMotion.Scheduler(unscaled: true))
				.WithImmediateBind(false)
				.WithOnComplete(() =>
				{
					if (!disableOnlyJacketOnFinish && playVersion == _playVersion)
					{
						_animation = default;
						gameObject.SetActive(false);
						onFinish?.Invoke();
					}
				})
				.Bind(elapsed =>
				{
					if (previous < fadeInEnd && elapsed >= fadeInEnd && onFinishViewGroupFade != null)
					{
						Render(fadeInEnd);
						onFinishViewGroupFade();
					}

					if (playVersion == _playVersion)
					{
						Render(elapsed);
					}
				});
		}

		private static void SetPositionX(RectTransform rect, float x)
		{
			Vector2 position = rect.anchoredPosition;
			position.x = x;
			rect.anchoredPosition = position;
		}

		private static void SetScaleX(RectTransform rect, float x)
		{
			Vector3 scale = rect.localScale;
			scale.x = x;
			rect.localScale = scale;
		}

		private static void SetScaleY(RectTransform rect, float y)
		{
			Vector3 scale = rect.localScale;
			scale.y = y;
			rect.localScale = scale;
		}

		public void FadeViewGroup(float alpha)
		{
			if (viewGroup != null)
			{
				viewGroup.alpha = alpha;
			}
		}

		private void OnDisable()
		{
			CancelAnimation();
		}

		/// <summary>Remembers where the prefab puts each animated element, before anything moves it.</summary>
		private void CacheLayout()
		{
			if (_hasLayoutCache)
			{
				return;
			}
			_hasLayoutCache = true;
			if (textColumn != null)
			{
				_textColumnBasePosition = textColumn.anchoredPosition;
				_textColumnPosition = _textColumnBasePosition;
			}
			if (jacketGroup != null)
			{
				_jacketBasePosition = ((RectTransform)jacketGroup.transform).anchoredPosition;
			}
			int count = infoGroup?.Length ?? 0;
			_rowBasePositions = new Vector2[count];
			for (int i = 0; i < count; i++)
			{
				if (infoGroup[i] != null)
				{
					_rowBasePositions[i] = ((RectTransform)infoGroup[i].transform).anchoredPosition;
				}
			}
		}

		/// <summary>Puts every animated element at the start of the timeline.</summary>
		private void ResetToHidden()
		{
			// The exit drifts the column left; a retry replays on the same view, so put it back.
			if (textColumn != null)
			{
				textColumn.anchoredPosition = _textColumnPosition;
			}
			if (viewGroup != null)
			{
				viewGroup.alpha = 0f;
			}
			if (band != null)
			{
				band.localScale = new Vector3(1f, 0f, 1f);
			}
			if (bandEdges != null)
			{
				foreach (RectTransform edge in bandEdges)
				{
					if (edge != null)
					{
						edge.localScale = new Vector3(0f, 1f, 1f);
					}
				}
			}
			if (jacketGroup != null)
			{
				jacketGroup.alpha = 0f;
				RectTransform jacketRect = (RectTransform)jacketGroup.transform;
				jacketRect.anchoredPosition = _jacketBasePosition + new Vector2(JACKET_SLIDE_X, 0f);
				jacketRect.localScale = Vector3.one * 1.06f;
			}
			if (shine != null)
			{
				shine.anchoredPosition = new Vector2(-SHINE_TRAVEL_X, shine.anchoredPosition.y);
			}
			if (rule != null)
			{
				rule.localScale = new Vector3(0f, 1f, 1f);
			}
			if (infoGroup != null)
			{
				for (int i = 0; i < infoGroup.Length; i++)
				{
					CanvasGroup row = infoGroup[i];
					if (row == null)
					{
						continue;
					}
					row.alpha = 0f;
					((RectTransform)row.transform).anchoredPosition = _rowBasePositions[i] + new Vector2(ROW_SLIDE_X, 0f);
				}
			}
			if (sparkles != null)
			{
				foreach (RectTransform sparkle in sparkles)
				{
					if (sparkle != null)
					{
						sparkle.localScale = Vector3.zero;
						sparkle.localRotation = Quaternion.identity;
					}
				}
			}
		}

		internal void CancelAnimation()
		{
			_playVersion++;
			_animation.TryCancel();
		}

		private static string ResolveVocalText(MasterMusicVocal vocal, string fallback)
		{
			if (vocal == null)
			{
				return fallback ?? string.Empty;
			}

			if (string.Equals(vocal.musicVocalType, MusicVocalType.instrumental.ToString(), StringComparison.OrdinalIgnoreCase))
			{
				return WordingManager.Get(INSTRUMENTAL_VOCAL_NAMES_WORDING_KEY);
			}

			if (!string.IsNullOrEmpty(vocal.caption))
			{
				return vocal.caption;
			}

			return fallback ?? string.Empty;
		}

		private static string ResolveCollaborationLabel(FreeLiveBootData freeLiveBootData, bool isCustomScore)
		{
			if (isCustomScore && freeLiveBootData != null)
			{
				return freeLiveBootData.CustomMusicScoreCollaborationLabel;
			}

			return string.Empty;
		}

		private static Texture2D LoadJacketTexture(LiveBootDataBase bootData, LiveMusicData musicData)
		{
			Texture2D customTexture = LiveMediaFiles.LoadCustomJacketTexture(bootData as FreeLiveBootData);
			if (customTexture != null)
			{
				return customTexture;
			}

			int musicId = musicData?.Music?.id ?? 0;
			string resourceName = musicId > 0 ? $"jacket_s_{musicId}" : null;
			if (string.IsNullOrEmpty(resourceName))
			{
				return null;
			}

			Texture2D texture = AssetBundleUtility.LoadAsset<Texture2D>("thumbnail/music_jacket", resourceName, false);
			if (texture == null)
			{
				texture = AssetBundleUtility.LoadAsset<Texture2D>("startapp/thumbnail/music_jacket", resourceName, false);
			}
			return texture;
		}


